v1 = """In our test setup, an agent goes through three distinct stages: training, distraction, and testing. To simulate an operational bug, the system returns a failure code when the agent picks a bad tool. In the distraction stage, the user asks up to 120 unrelated questions. We then measure whether the model still repeats the failing tool. The language model generates its tool call by predicting next tokens sequentially according to the probability equation in (5)."""

check("V1", v1)

