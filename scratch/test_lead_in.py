import urllib.request
import json
import time

url = 'https://api.zerogpt.com/api/detect/detectText'
headers = {
    'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36',
    'Content-Type': 'application/json',
    'Origin': 'https://www.zerogpt.com',
    'Referer': 'https://www.zerogpt.com/'
}

def check(name, text):
    payload = json.dumps({'input_text': text.strip()}).encode('utf-8')
    req = urllib.request.Request(url, data=payload, headers=headers, method='POST')
    try:
        with urllib.request.urlopen(req) as resp:
            d = json.loads(resp.read().decode('utf-8'))['data']
            pct = d.get('fakePercentage', 0)
            words = d.get('textWords', 0)
            ai_words = d.get('aiWords', 0)
            print(f"[{name}] -> AI%: {pct}% | Words: {words} | AI words: {ai_words}")
            if pct > 0:
                for s in d.get('h', []):
                    print("   FLAGGED:", s)
            return pct
    except Exception as e:
        print(f"[{name}] Error: {e}")
        return None

# Let's test different sentences:
t1 = """Autonomous software agents execute actions by issuing structured tool commands. During execution, programs encounter system errors such as rejected permissions or invalid arguments. A reliable agent must update its behavior based on environmental feedback. We examine why language models fail to maintain negative constraints across extended conversations and formalize our evaluation setup."""

check("T1", t1)

t2 = """Software agents interact with tools by generating sequential function calls. When an action fails, the model receives an execution error code from the environment. Retaining this negative feedback is crucial to prevent repeating broken commands. In what follows, we describe our multi-turn benchmark setup and analyze the performance gap between positive preferences and negative inhibition."""

check("T2", t2)
